/**
 * @file dependency-graph.test.ts
 * @description Unit tests for the DependencyGraphBuilder.
 * Run with: npx ts-node src/__tests__/dependency-graph.test.ts
 */

import assert from 'assert';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { DependencyGraphBuilder } from '../engine/dependency-graph';

// =============================================================================
// HELPERS
// =============================================================================

function makeTempDir(): string {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'dep-graph-test-'));
}

function writeFile(dir: string, name: string, content: string): void {
  fs.writeFileSync(path.join(dir, name), content, 'utf8');
}

// =============================================================================
// FIXTURES
// =============================================================================

const PACKAGE_LOCK_V2 = JSON.stringify({
  name: 'my-app',
  version: '1.0.0',
  lockfileVersion: 2,
  requires: true,
  packages: {
    '': { name: 'my-app', version: '1.0.0' },
    'node_modules/lodash': { version: '4.17.21', resolved: 'https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz' },
    'node_modules/express': { version: '4.18.2', resolved: 'https://registry.npmjs.org/express/-/express-4.18.2.tgz' },
    'node_modules/axios': { version: '1.6.0', resolved: 'https://registry.npmjs.org/axios/-/axios-1.6.0.tgz' },
    'node_modules/jest': { version: '29.0.0', dev: true },
    'node_modules/typescript': { version: '5.0.0', dev: true },
  },
});

const YARN_LOCK_V1 = `
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.

"lodash@^4.17.0", "lodash@^4.17.21":
  version "4.17.21"
  resolved "https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz"
  integrity sha512-abc

express@^4.18.0:
  version "4.18.2"
  resolved "https://registry.npmjs.org/express/-/express-4.18.2.tgz"

chalk@^5.0.0:
  version "5.3.0"
  resolved "https://registry.npmjs.org/chalk/-/chalk-5.3.0.tgz"
`;

const REQUIREMENTS_TXT = `
# Production dependencies
requests==2.28.0
flask>=2.3.0,<3.0
Django~=4.2.0
boto3==1.26.0
`;

// =============================================================================
// TEST RUNNER
// =============================================================================

let passed = 0;
let failed = 0;

function test(name: string, fn: () => Promise<void>) {
  return fn().then(() => {
    console.log(`  PASS  ${name}`);
    passed++;
  }).catch((e: Error) => {
    console.error(`  FAIL  ${name}\n        ${e.message}`);
    failed++;
  });
}

// =============================================================================
// TESTS
// =============================================================================

console.log('\nRunning DependencyGraphBuilder Tests...\n');

async function runAll(): Promise<void> {
  const builder = new DependencyGraphBuilder();

  // ── package-lock.json v2 ──────────────────────────────────────────────────

  await test('A1 — parses package-lock.json v2 with 5 packages (2 dev)', async () => {
    const dir = makeTempDir();
    try {
      writeFile(dir, 'package-lock.json', PACKAGE_LOCK_V2);
      writeFile(dir, 'package.json', '{}');
      const graph = await builder.build(dir);

      assert.strictEqual(graph.packages.length, 5);
      assert.ok(graph.lockfilesFound.includes('package-lock.json'));

      const lodash = graph.packages.find((p) => p.name === 'lodash');
      assert.ok(lodash, 'lodash should be present');
      assert.strictEqual(lodash!.version, '4.17.21');
      assert.strictEqual(lodash!.isDev, false);
      assert.strictEqual(lodash!.ecosystem, 'npm');

      const devPkgs = graph.packages.filter((p) => p.isDev);
      assert.strictEqual(devPkgs.length, 2);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  await test('A2 — package-lock.json v2 populates npm ecosystem', async () => {
    const dir = makeTempDir();
    try {
      writeFile(dir, 'package-lock.json', PACKAGE_LOCK_V2);
      writeFile(dir, 'package.json', '{}');
      const graph = await builder.build(dir);
      assert.ok(graph.ecosystems.has('npm'));
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  // ── yarn.lock ─────────────────────────────────────────────────────────────

  await test('B1 — parses yarn.lock v1 with 3 distinct packages', async () => {
    const dir = makeTempDir();
    try {
      writeFile(dir, 'yarn.lock', YARN_LOCK_V1);
      writeFile(dir, 'package.json', '{}');
      const graph = await builder.build(dir);

      const lodashPkgs = graph.packages.filter((p) => p.name === 'lodash');
      assert.strictEqual(lodashPkgs.length, 1, 'lodash should deduplicate to 1');
      assert.strictEqual(lodashPkgs[0]!.version, '4.17.21');

      const names = graph.packages.map((p) => p.name);
      assert.ok(names.includes('express'));
      assert.ok(names.includes('chalk'));
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  // ── requirements.txt ─────────────────────────────────────────────────────

  await test('C1 — parses requirements.txt with pinned, range, and comment lines', async () => {
    const dir = makeTempDir();
    try {
      writeFile(dir, 'requirements.txt', REQUIREMENTS_TXT);
      const graph = await builder.build(dir);
      const pyPkgs = graph.packages.filter((p) => p.ecosystem === 'pypi');

      assert.strictEqual(pyPkgs.length, 4);

      const req = pyPkgs.find((p) => p.name === 'requests');
      assert.ok(req, 'requests should be present');
      assert.strictEqual(req!.version, '2.28.0');
      assert.ok(req!.requestedVersion.includes('=='));
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  // ── Missing lock file ─────────────────────────────────────────────────────

  await test('D1 — flags package.json with no lock file as missing', async () => {
    const dir = makeTempDir();
    try {
      writeFile(dir, 'package.json', JSON.stringify({ name: 'no-lock' }));
      const graph = await builder.build(dir);
      assert.ok(graph.missingLockfiles.includes('package.json'));
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  await test('D2 — does NOT flag package.json as missing when package-lock.json exists', async () => {
    const dir = makeTempDir();
    try {
      writeFile(dir, 'package.json', '{}');
      writeFile(dir, 'package-lock.json', PACKAGE_LOCK_V2);
      const graph = await builder.build(dir);
      assert.ok(!graph.missingLockfiles.includes('package.json'));
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  // ── Parse error handling ──────────────────────────────────────────────────

  await test('E1 — malformed JSON adds to parseErrors and does not throw', async () => {
    const dir = makeTempDir();
    try {
      writeFile(dir, 'package-lock.json', '{ this is not json !!!');
      writeFile(dir, 'package.json', '{}');
      const graph = await builder.build(dir);
      assert.ok(graph.parseErrors.length > 0, 'Should have a parse error');
      assert.strictEqual(graph.parseErrors[0]!.file, 'package-lock.json');
      assert.strictEqual(graph.packages.length, 0);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  // ── Empty repo ────────────────────────────────────────────────────────────

  await test('F1 — empty repo returns all-empty graph', async () => {
    const dir = makeTempDir();
    try {
      const graph = await builder.build(dir);
      assert.strictEqual(graph.packages.length, 0);
      assert.strictEqual(graph.lockfilesFound.length, 0);
      assert.strictEqual(graph.missingLockfiles.length, 0);
      assert.strictEqual(graph.parseErrors.length, 0);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  console.log(`\nResults: ${passed} passed, ${failed} failed out of ${passed + failed} tests`);
  if (failed > 0) process.exit(1);
}

runAll().catch((e) => { console.error(e); process.exit(1); });
