import { githubAppAuth } from './app-auth';

export interface ManualFixInstruction {
  ruleId: string;
  filePath: string;
  guidance: string;
  referenceUrl?: string;
  currentCode?: string;
}

class PatchCommitter {
  async commitPatchDoc(params: {
    installationId: number;
    owner: string;
    repo: string;
    branch: string;
    scanId: string;
    manualFixes: ManualFixInstruction[];
    appliedFixes: Array<{ ruleId: string; filePath: string }>;
  }): Promise<{ commitUrl: string; commitSha: string }> {
    const octokit = await githubAppAuth.getInstallationOctokit(params.installationId);
    const content = this.buildPatchDoc(params);

    const path = '.github/cicd-reliability/patches.md';
    let existingSha: string | undefined;

    try {
      const existing = await octokit.rest.repos.getContent({
        owner: params.owner,
        repo: params.repo,
        path,
        ref: params.branch
      });
      existingSha = (existing.data as { sha: string }).sha;
    } catch (err) {
      // File does not exist yet, which is expected
    }

    const { data } = await octokit.rest.repos.createOrUpdateFileContents({
      owner: params.owner,
      repo: params.repo,
      path,
      message: `docs: CI/CD reliability findings for scan ${params.scanId.slice(0, 8)}`,
      content: Buffer.from(content).toString('base64'),
      branch: params.branch,
      ...(existingSha ? { sha: existingSha } : {}),
      committer: {
        name: 'CI/CD Reliability Bot',
        email: 'bot@cicd-reliability.io'
      }
    });

    return {
      commitUrl: data.commit.html_url ?? '',
      commitSha: data.commit.sha ?? ''
    };
  }

  private buildPatchDoc(params: {
    scanId: string;
    manualFixes: ManualFixInstruction[];
    appliedFixes: Array<{ ruleId: string; filePath: string }>;
  }): string {
    const appliedList = params.appliedFixes.length > 0
      ? params.appliedFixes.map(f => `- **Rule**: \`${f.ruleId}\` in \`${f.filePath}\``).join('\n')
      : '*No fixes were automatically applied.*';

    const manualList = params.manualFixes.length > 0
      ? params.manualFixes.map((f, idx) => {
          const ref = f.referenceUrl ? `\n- **Reference**: [Documentation](${f.referenceUrl})` : '';
          const codeSnippet = f.currentCode
            ? `\n\n**Current Code:**\n\`\`\`yaml\n${f.currentCode}\n\`\`\``
            : '';
          
          return `### ${idx + 1}. Rule: \`${f.ruleId}\` in \`${f.filePath}\`
- **Guidance**: ${f.guidance}${ref}${codeSnippet}

*(Note: The above code snippet is for illustration of the finding location. Apply necessary adjustments manually.)*`;
        }).join('\n\n---\n\n')
      : '*No manual fixes are required.*';

    return `# CI/CD Reliability Scan Findings & Patches

This document outlines the results of the CI/CD reliability scan with ID \`${params.scanId}\`.

## 🔧 Automatically Applied Fixes

The following issues were corrected automatically in this branch:

${appliedList}

## ⚠️ Manual Review & Fixes Required

The following issues cannot be automatically resolved safely and require manual intervention:

${manualList}

---
*Generated by the CI/CD Reliability Platform*
`;
  }
}

export const patchCommitter = new PatchCommitter();
export default patchCommitter;
