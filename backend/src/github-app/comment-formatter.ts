// @ts-nocheck
export function formatPRComment(
  scan: any,
  _repoUrl: string,
  dashboardUrl: string
): string {
  const getTrend = () => {
    // If we had history, we would compute trend. For now just mock it.
    if (scan.riskGrade === 'A' || scan.riskGrade === 'B') return '↑ improving';
    return '→ stable';
  };

  const getCelebratoryNote = () => {
    if (scan.riskGrade === 'A' || scan.riskGrade === 'B') {
      return '\n✅ **No critical issues found.** Great job keeping your pipeline reliable!';
    }
    if (scan.riskGrade === 'F') {
      return '\n⛔ **Critical issues require immediate attention.** Please review the findings below.';
    }
    return '';
  };

  let criticalHighFindings = scan.findings.critical.concat(scan.findings.high).slice(0, 5);
  let findingsTable = '';

  if (criticalHighFindings.length > 0) {
    findingsTable = `
### Critical & High Findings

| Rule | File | Issue |
|------|------|-------|
${criticalHighFindings.map(f => `| \`${f.ruleId}\` | \`${f.filePath}\` | ${f.title} |`).join('\n')}
`;
  }

  let aiSection = '';
  if (scan.analysisReport?.summary) {
    aiSection = `
---

### AI Analysis

> ${scan.analysisReport.summary.replace(/\n/g, '\n> ')}
`;
  }

  const findingDetails = scan.findings.all.map(f => {
    return `<details>
<summary><strong>${getSeverityEmoji(f.severity)} ${f.title}</strong> (\`${f.ruleId}\`)</summary>

**File**: \`${f.filePath}${f.line ? `:${f.line}` : ''}\`
**Category**: ${f.category}

${f.description}

**Remediation**:
${f.remediation}
</details>`;
  }).join('\n\n');

  return `## CI/CD Reliability Analysis

<!-- cicd-reliability-report -->

**Risk Grade: ${scan.riskGrade}** | Score: ${scan.riskScore}/100 | ${getTrend()}
${getCelebratoryNote()}

---

### Summary

| Severity | Count |
|----------|-------|
| 🔴 Critical | ${scan.criticalCount} |
| 🟠 High | ${scan.highCount} |
| 🟡 Medium | ${scan.mediumCount} |
| 🔵 Low | ${scan.lowCount} |
${findingsTable}${aiSection}
---

[View full report →](${dashboardUrl}/repos/${scan.repoId}/scans/${scan.id}) | [View DAG →](${dashboardUrl}/repos/${scan.repoId}/scans/${scan.id}/dag)

---
<details>
<summary>View all ${scan.totalFindings} findings</summary>

${findingDetails}

</details>

<details>
<summary>About this report</summary>
Generated by CI/CD Reliability Intelligence Platform.
Scan ID: ${scan.id} | Branch: ${scan.branch} | ${new Date(scan.triggeredAt).toLocaleString()}
</details>
`;
}

function getSeverityEmoji(sev: string) {
  switch(sev) {
    case 'critical': return '🔴';
    case 'high': return '🟠';
    case 'medium': return '🟡';
    case 'low': return '🔵';
    default: return '⚪';
  }
}
